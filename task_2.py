# Введите пароль, проверьте и выведите на экран:
#  Если меньше 16 символов – «Слишком короткий».
#  Если содержит только буквы или только цифры – «Слабый пароль».
#  Иначе – «Надежный пароль».

password=input("Введите надёжный пароль (более 16 символов с буквами и цифрами):")
IsGood=True
if len(password)<16:
    print("Слишком короткий")
    IsGood=False
if password.isalpha() or password.isdigit():
    print("Слабый пароль")
    IsGood=False
if IsGood:
    print("Надежный пароль")
